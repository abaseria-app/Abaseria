picked as (
  select p.id,
    coalesce(
      (select nullif(m.brand, '') from map m
        where lower(p.name) = lower(m.prefix) or lower(p.name) like lower(m.prefix) || ' %'
        order by length(m.prefix) desc limit 1),
      case when exists (select 1 from map m where lower(p.name) = lower(m.prefix) or lower(p.name) like lower(m.prefix) || ' %')
           then null
           when lower(split_part(btrim(p.name), ' ', 1)) in ('super', 'choco', 'chocolate', 'creamy', 'ube', 'pan', 'potato', 'green', 'san', 'white', 'lucky', 'good', 'cafe', 'coca', 'bounty', 'test', 'cooler', 'apple', 'sponge', 'frozen', 'sliced', 'whole', 'red', 'strawberry', 'sweet', 'twisted', 'tuna', 'banana', 'cheese', 'egg', 'locally', 'savory', 'ribbed') then null
           else split_part(btrim(p.name), ' ', 1) end
    ) as brand
  from public.products p
  where p.brand is null
)
update public.products p set brand = picked.brand
from picked where picked.id = p.id and picked.brand is not null;

-- Barcodes starting 4800194 are Liwayway (Oishi). Their names often leave the brand off ("Potato Fries").
update public.products set brand = 'Oishi' where brand is null and barcode like '4800194%';

update public.products set kind = 'multipack'
where kind = 'single'
  and (size ~* '^\s*[0-9]+\s*[x×]\s*[0-9]'
       or name ~* '(multipack|multi-pack|twin pack|pack of [0-9]+|\m[0-9]+s pack|\m[0-9]+-pack)');

update public.products set kind = 'bundle'
where kind = 'single' and name ~* '\mkit\M';
